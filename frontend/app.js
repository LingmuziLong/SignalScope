// ==================== WebSocket 事件处理 WebSocket event handling====================
ws.onmessage = function(event) {
    const d = JSON.parse(event.data);
    if (Array.isArray(d.nodes)) {
        const newCount = d.nodes.length;
        if (newCount !== NODE_COUNT) {
            NODE_COUNT = newCount;
            nodeCountInput.value = NODE_COUNT;
            saveNodeCountSetting();
            currentPairIndex = 0;
            updatePairLabel();
            if (latestNodesData) {
                updateDisplayedNodes(latestNodesData);
            }
        }
        latestNodesData = d.nodes;
        updateDisplayedNodes(latestNodesData);
    }
    if (d.current_node) {
        currentNodeType = d.current_node;
        updateCurrentNodeDisplay();
    }
};

ws.onopen = function() {
    console.log('WebSocket 连接已建立');
    ws.send(JSON.stringify({ action: 'switch_node', node: currentNodeType }));
    if (NODE_COUNT !== 20) {
        ws.send(JSON.stringify({ action: 'set_node_count', count: NODE_COUNT }));
    }
};

ws.onerror = (error) => console.error("WebSocket 错误:", error);
ws.onclose = () => console.log("WebSocket 连接已关闭");

