// ==================== 保存和加载设置 Save and load settings====================
function loadSettings() {
    const savedInterval = localStorage.getItem('signalScopeInterval');
    if (savedInterval) {
        let sec = parseInt(savedInterval, 10);
        if (!isNaN(sec) && sec >= 1 && sec <= 60) {
            PAIR_DURATION = sec * 1000;
            intervalInput.value = sec;
        }
    }
    const savedNodeCount = localStorage.getItem('signalScopeNodeCount');
    if (savedNodeCount) {
        let cnt = parseInt(savedNodeCount, 10);
        if (!isNaN(cnt) && cnt >= 1 && cnt <= 100) {
            NODE_COUNT = cnt;
            nodeCountInput.value = cnt;
            if (ws.readyState === WebSocket.OPEN) {
                ws.send(JSON.stringify({ action: 'set_node_count', count: cnt }));
            }
        }
    }
}

