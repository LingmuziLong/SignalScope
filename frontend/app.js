// ==================== 节点名称存储与辅助函数 Node name storage and auxiliary functions====================
function loadNodeNames() {
    const stored = localStorage.getItem('signalScopeNodeNames');
    if (stored) {
        try {
            return JSON.parse(stored);
        } catch(e) { return {}; }
    }
    return {};
}

function saveNodeNames(namesMap) {
    localStorage.setItem('signalScopeNodeNames', JSON.stringify(namesMap));
}

function getNodeDisplayName(nodeNumber) {
    const names = loadNodeNames();
    if (names[nodeNumber]) {
        return names[nodeNumber];
    }
    const t = translations[currentLang];
    return currentLang === 'zh' ? `节点 ${nodeNumber}` : `Node ${nodeNumber}`;
}

function setNodeName(nodeNumber, customName) {
    if (!customName || customName.trim() === "") return;
    const names = loadNodeNames();
    names[nodeNumber] = customName.trim();
    saveNodeNames(names);
    const idx1 = currentPairIndex * 2 + 1;
    const idx2 = currentPairIndex * 2 + 2;
    if (nodeNumber === idx1) nodeNameSpan1.innerText = customName.trim();
    if (nodeNumber === idx2 && idx2 <= NODE_COUNT) nodeNameSpan2.innerText = customName.trim();
    updatePairLabel();
}

// ==================== 辅助函数 auxiliary functions====================
function updatePairLabel() {
    const idx1 = currentPairIndex * 2 + 1;
    const idx2 = currentPairIndex * 2 + 2;
    const t = translations[currentLang];
    const prefix = currentLang === 'zh' ? '节点 ' : 'Node ';
    if (idx2 <= NODE_COUNT) {
        pairLabelSpan.innerText = `${prefix}${idx1} & ${prefix}${idx2}`;
    } else {
        pairLabelSpan.innerText = `${prefix}${idx1}`;
    }
    nodeNameSpan1.innerText = getNodeDisplayName(idx1);
    if (idx2 <= NODE_COUNT) {
        nodeNameSpan2.innerText = getNodeDisplayName(idx2);
    } else {
        nodeNameSpan2.innerText = getNodeDisplayName(idx2);
    }
}

function switchToPairByIndex(pairIndex) {
    const totalPairs = getTotalPairs();
    if (totalPairs === 0) return;
    pairIndex = (pairIndex + totalPairs) % totalPairs;
    currentPairIndex = pairIndex;
    updatePairLabel();
    resetCountdownDisplay();
    if (latestNodesData) {
        updateDisplayedNodes(latestNodesData);
    }
}

function nextPair() {
    const nextIndex = (currentPairIndex + 1) % getTotalPairs();
    switchToPairByIndex(nextIndex);
    resetAutoTimer();
}

function prevPair() {
    const total = getTotalPairs();
    const prevIndex = (currentPairIndex - 1 + total) % total;
    switchToPairByIndex(prevIndex);
    resetAutoTimer();
}

function resetAutoTimer() {
    if (timer) clearTimeout(timer);
    if (autoPlay) {
        timer = setTimeout(() => {
            nextPair();
        }, PAIR_DURATION);
    }
    startCountdown();
}

function startCountdown() {
    if (countdownInterval) clearInterval(countdownInterval);
    if (!autoPlay) {
        countdownSpan.innerText = '--' + translations[currentLang].countdownSuffix;
        return;
    }
    let remaining = Math.ceil(PAIR_DURATION / 1000);
    countdownSpan.innerText = `${remaining}${translations[currentLang].countdownSuffix}`;
    countdownInterval = setInterval(() => {
        if (!autoPlay) {
            if (countdownInterval) clearInterval(countdownInterval);
            return;
        }
        remaining -= 1;
        if (remaining <= 0) {
            clearInterval(countdownInterval);
            countdownSpan.innerText = `0${translations[currentLang].countdownSuffix}`;
        } else {
            countdownSpan.innerText = `${remaining}${translations[currentLang].countdownSuffix}`;
        }
    }, 1000);
}

function resetCountdownDisplay() {
    if (countdownInterval) clearInterval(countdownInterval);
    if (autoPlay) {
        startCountdown();
    } else {
        countdownSpan.innerText = '--' + translations[currentLang].countdownSuffix;
    }
}

function toggleAutoPlay() {
    autoPlay = !autoPlay;
    const t = translations[currentLang];
    if (autoPlay) {
        playPauseBtn.innerText = t.playPause.playing;
        playPauseBtn.classList.remove('paused');
        resetAutoTimer();
    } else {
        playPauseBtn.innerText = t.playPause.paused;
        playPauseBtn.classList.add('paused');
        if (timer) clearTimeout(timer);
        if (countdownInterval) clearInterval(countdownInterval);
        countdownSpan.innerText = '--' + t.countdownSuffix;
    }
}

function saveInterval() {
    let newSeconds = parseInt(intervalInput.value, 10);
    if (isNaN(newSeconds)) newSeconds = 10;
    newSeconds = Math.min(60, Math.max(1, newSeconds));
    intervalInput.value = newSeconds;
    PAIR_DURATION = newSeconds * 1000;
    saveIntervalSetting();
    if (autoPlay) {
        resetAutoTimer();
    } else {
        if (timer) clearTimeout(timer);
        if (countdownInterval) clearInterval(countdownInterval);
        countdownSpan.innerText = '--' + translations[currentLang].countdownSuffix;
    }
}

function setNodeCount(newCount) {
    if (newCount === NODE_COUNT) return;
    if (ws.readyState === WebSocket.OPEN) {
        ws.send(JSON.stringify({ action: 'set_node_count', count: newCount }));
    } else {
        console.warn('WebSocket not open');
    }
    saveNodeCountSetting();
}

// ==================== HiDPI 自适应画布设置 HiDPI adaptive canvas settings====================
function setupHiDPICanvas(canvas) {
    const container = canvas.parentElement;
    if (!container) return null;
    const rect = container.getBoundingClientRect();
    let width = rect.width;
    let height = rect.height;
    if (width <= 0 || height <= 0) {
        width = 300;
        height = 200;
    }
    const dpr = window.devicePixelRatio || 1;
    canvas.style.width = width + 'px';
    canvas.style.height = height + 'px';
    canvas.width = Math.floor(width * dpr);
    canvas.height = Math.floor(height * dpr);
    const ctx = canvas.getContext('2d');
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.scale(dpr, dpr);
    canvas.dpr = dpr;
    canvas.logicalWidth = width;
    canvas.logicalHeight = height;
    return ctx;
}

function resizeAllCanvases() {
    const canvases = [timeCanvas1, freqCanvas1, histCanvas1, timeCanvas2, freqCanvas2, histCanvas2];
    canvases.forEach(c => { if (c) setupHiDPICanvas(c); });
}

// ==================== 绘图函数 plotting function====================
function drawFixedAxes(ctx, config) {
    const canvas = ctx.canvas;
    const dpr = canvas.dpr || 1;
    const width = canvas.logicalWidth || (canvas.width / dpr);
    const height = canvas.logicalHeight || (canvas.height / dpr);
    const plotWidth = width - margin.left - margin.right;
    const plotHeight = height - margin.top - margin.bottom;

    ctx.clearRect(0, 0, width, height);
    ctx.fillStyle = "white";
    ctx.fillRect(0, 0, width, height);

    ctx.strokeStyle = "#000";
    ctx.lineWidth = 1.2;
    ctx.fillStyle = "#000";

    const left = Math.floor(margin.left);
    const top = Math.floor(margin.top);
    const right = Math.floor(width - margin.right);
    const bottom = Math.floor(height - margin.bottom);

    ctx.strokeRect(left, top, right - left, bottom - top);
    ctx.font = "12px Arial, sans-serif";
    ctx.fillStyle = "#000";
    ctx.textAlign = "center";
    ctx.textBaseline = "top";

    config.x.ticks.forEach(tick => {
        const x = Math.floor(left + (tick - config.x.min) / (config.x.max - config.x.min) * plotWidth);
        ctx.beginPath();
        ctx.moveTo(x, bottom);
        ctx.lineTo(x, bottom + 5);
        ctx.stroke();
        const labelY = bottom + 8;
        if (labelY < height - 5) ctx.fillText(tick.toString(), x, labelY);
        if (tick !== config.x.min && tick !== config.x.max) {
            ctx.strokeStyle = "#e0e0e0";
            ctx.lineWidth = 1;
            ctx.beginPath();
            ctx.moveTo(x, top);
            ctx.lineTo(x, bottom);
            ctx.stroke();
            ctx.strokeStyle = "#000";
            ctx.lineWidth = 1.2;
        }
    });

    ctx.font = "bold 13px 'Microsoft YaHei', SimHei, sans-serif";
    const xLabelText = config.x.label + (config.x.unit ? ` (${config.x.unit})` : '');
    const xLabelY = bottom + 25;
    if (xLabelY < height - 2) ctx.fillText(xLabelText, width / 2, xLabelY);

    ctx.textAlign = "right";
    ctx.textBaseline = "middle";
    ctx.font = "12px Arial, sans-serif";
    config.y.ticks.forEach(tick => {
        const y = Math.floor(bottom - (tick - config.y.min) / (config.y.max - config.y.min) * plotHeight);
        ctx.beginPath();
        ctx.moveTo(left - 5, y);
        ctx.lineTo(left, y);
        ctx.stroke();
        ctx.fillText(tick.toString(), left - 8, y);
        if (tick !== config.y.min && tick !== config.y.max) {
            ctx.strokeStyle = "#e0e0e0";
            ctx.lineWidth = 1;
            ctx.beginPath();
            ctx.moveTo(left, y);
            ctx.lineTo(right, y);
            ctx.stroke();
            ctx.strokeStyle = "#000";
            ctx.lineWidth = 1.2;
        }
    });

    ctx.save();
    ctx.translate(20, height / 2);
    ctx.rotate(-Math.PI / 2);
    ctx.textAlign = "center";
    ctx.textBaseline = "middle";
    ctx.font = "bold 13px 'Microsoft YaHei', SimHei, sans-serif";
    const yLabelText = config.y.label + (config.y.unit ? ` (${config.y.unit})` : '');
    ctx.fillText(yLabelText, 0, 0);
    ctx.restore();
}

function drawLinePlot(canvas, data, color, config) {
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    const dpr = canvas.dpr || 1;
    const width = canvas.width / dpr;
    const height = canvas.height / dpr;
    const plotWidth = width - margin.left - margin.right;
    const plotHeight = height - margin.top - margin.bottom;
    ctx.clearRect(0, 0, width, height);
    ctx.fillStyle = "white";
    ctx.fillRect(0, 0, width, height);
    drawFixedAxes(ctx, config);
    if (data && data.length > 0) {
        ctx.beginPath();
        ctx.strokeStyle = color;
        ctx.lineWidth = 1.8;
        const points = [];
        const n = data.length;
        for (let i = 0; i < n; i++) {
            const xVal = config.x.min + (i / (n - 1)) * (config.x.max - config.x.min);
            const x = margin.left + (xVal - config.x.min) / (config.x.max - config.x.min) * plotWidth;
            const y = height - margin.bottom - (data[i] - config.y.min) / (config.y.max - config.y.min) * plotHeight;
            points.push({ x, y, val: data[i], xVal, index: i });
            if (i === 0) ctx.moveTo(x, y);
            else ctx.lineTo(x, y);
        }
        ctx.stroke();
        canvas.config = config;
        canvas.dataPoints = points;
    } else {
        canvas.config = config;
        canvas.dataPoints = [];
    }
}

function drawHistogram(canvas, data, config) {
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    const dpr = canvas.dpr || 1;
    const width = canvas.width / dpr;
    const height = canvas.height / dpr;
    const plotWidth = width - margin.left - margin.right;
    const plotHeight = height - margin.top - margin.bottom;
    ctx.clearRect(0, 0, width, height);
    ctx.fillStyle = "white";
    ctx.fillRect(0, 0, width, height);
    drawFixedAxes(ctx, config);
    if (data && data.length > 0) {
        const bins = 50;
        const binWidth = (config.x.max - config.x.min) / bins;
        const counts = new Array(bins).fill(0);
        data.forEach(val => {
            if (val >= config.x.min && val <= config.x.max) {
                const idx = Math.min(Math.floor((val - config.x.min) / binWidth), bins - 1);
                counts[idx]++;
            }
        });
        const maxCount = Math.max(...counts) || 1;
        const barWidth = plotWidth / bins;
        ctx.fillStyle = "steelblue";
        const bars = [];
        counts.forEach((count, i) => {
            const pct = (count / maxCount) * 100;
            const h = (pct / 100) * plotHeight;
            const x = margin.left + i * barWidth;
            const y = height - margin.bottom - h;
            if (h > 0.5) {
                ctx.fillRect(x + 1, y, barWidth - 2, h);
                bars.push({
                    x1: x + 1, x2: x + barWidth - 2, y1: y, y2: height - margin.bottom,
                    count: count, percentage: pct.toFixed(1), xVal: config.x.min + (i + 0.5) * binWidth
                });
            }
        });
        canvas.histBars = bars;
    } else {
        canvas.histBars = [];
    }
    canvas.config = config;
}

function setupMouseInteraction(canvas, isHistogram = false) {
    if (!canvas) return;
    canvas.addEventListener('click', function(e) {
        const rect = canvas.getBoundingClientRect();
        const config = canvas.config;
        if (!config) return;
        const logicalX = (e.clientX - rect.left) * (canvas.width / rect.width) / (canvas.dpr || 1);
        const logicalY = (e.clientY - rect.top) * (canvas.height / rect.height) / (canvas.dpr || 1);
        let displayText = '';
        let found = false;
        if (isHistogram) {
            const bars = canvas.histBars || [];
            const t = translations[currentLang];
            for (let bar of bars) {
                if (logicalX >= bar.x1 && logicalX <= bar.x2 && logicalY >= bar.y1 && logicalY <= bar.y2) {
                    displayText = `${t.tooltipPrefixHist}: ${bar.xVal.toFixed(1)}  ${t.countLabel}: ${bar.count} (${bar.percentage}%)`;
                    found = true;
                    break;
                }
            }
        } else {
            const points = canvas.dataPoints || [];
            if (points.length) {
                const plotLeft = margin.left;
                const plotWidth = (canvas.width / (canvas.dpr || 1)) - margin.left - margin.right;
                const xVal = config.x.min + (logicalX - plotLeft) / plotWidth * (config.x.max - config.x.min);
                const dataIndex = Math.round((xVal - config.x.min) / (config.x.max - config.x.min) * (points.length - 1));
                if (dataIndex >= 0 && dataIndex < points.length) {
                    const point = points[dataIndex];
                    const dist = Math.hypot(logicalX - point.x, logicalY - point.y);
                    if (dist < 12) {
                        const prefix = (config === AXIS_CONFIG.time) ? translations[currentLang].tooltipPrefixTime : translations[currentLang].tooltipPrefixFreq;
                        displayText = `${prefix}: ${point.xVal.toFixed(1)}  ${config.y.label}: ${point.val.toFixed(1)}${config.y.unit}`;
                        found = true;
                    }
                }
            }
        }
        if (found) {
            tooltip.textContent = displayText;
            tooltip.style.display = 'block';
            tooltip.style.left = (e.clientX + 8) + 'px';
            tooltip.style.top = (e.clientY - 28) + 'px';
            setTimeout(() => tooltip.style.display = 'none', 3000);
        } else {
            tooltip.style.display = 'none';
        }
    });
}

